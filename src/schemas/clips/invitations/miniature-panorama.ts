import { z } from 'zod';
import { zColor, zSlider } from '../../control';
import { inviteScriptFontSchema, inviteSerifFontSchema } from '../../invite-common';
import { defaultMotion, motionSchema, promoMeta } from '../../promo-common';
import type { ClipMeta } from '../../registry';

const frames = (min = 0, max = 400) => zSlider({ min, max });

const unit = (max = 1, step = 0.01) => zSlider({ min: 0, max, step });

const count = (max: number) => zSlider({ min: 0, max, step: 1 });

export const miniaturePanoramaSchema = z.object({
  invite: z.object({
    show: z.boolean(),
    names: z.string(),
    line: z.string(),
    date: z.string(),
    scriptFont: inviteScriptFontSchema,
    serifFont: inviteSerifFontSchema,
    namesSize: zSlider({ min: 60, max: 260 }),
    lineSize: zSlider({ min: 14, max: 90 }),
    dateSize: zSlider({ min: 14, max: 110 }),
    tracking: unit(0.6),
    gap: zSlider({ min: 0, max: 160 }),
    centerY: zSlider({ min: 200, max: 1700 }),
    start: frames(0, 1500),
    rise: zSlider({ min: 0, max: 160 }),
    color: zColor(),
    glow: zColor(),
    glowStrength: unit(),
  }),
  timing: z.object({
    reveal: frames(10, 120),
    swans: frames(0),
    toLake: frames(20, 120),
    lake: frames(0),
    toNight: frames(20, 120),
    night: frames(0),
    toGarden: frames(20, 120),
    garden: frames(0),
    toPath: frames(20, 160),
    procession: frames(0),
    toFinale: frames(10, 90),
  }),
  camera: z.object({
    closeUp: zSlider({ min: 1, max: 2.4, step: 0.01 }),
    drift: unit(2, 0.05),
    parallax: unit(1.5),
    roll: zSlider({ min: 0, max: 12, step: 0.5 }),
    blur: unit(2, 0.05),
  }),
  sky: z.object({
    dayTop: zColor(),
    dayHorizon: zColor(),
    nightTop: zColor(),
    nightHorizon: zColor(),
    clouds: zColor(),
    cloudShade: zColor(),
    cloudCount: count(6),
    cloudSpeed: unit(4, 0.05),
  }),
  stars: z.object({ count: count(400), color: zColor() }),
  birds: z.object({ count: count(24), color: zColor() }),
  petals: z.object({ count: count(40), color: zColor() }),
  hills: z.object({ far: zColor(), near: zColor(), mist: zColor() }),
  lake: z.object({
    water: zColor(),
    ripple: zColor(),
    pad: zColor(),
    lotus: zColor(),
    lotusWhite: zColor(),
  }),
  swans: z.object({ show: z.boolean(), body: zColor(), beak: zColor() }),
  peacocks: z.object({
    show: z.boolean(),
    neck: zColor(),
    wing: zColor(),
    tail: zColor(),
    eyes: zColor(),
  }),
  railing: z.object({ marble: zColor(), shade: zColor() }),
  canopies: z.object({ roof: zColor(), motif: zColor(), fringe: zColor(), poles: zColor() }),
  pavilions: z.object({ stone: zColor(), shade: zColor() }),
  trees: z.object({
    dark: zColor(),
    mid: zColor(),
    light: zColor(),
    sprig: zColor(),
    blossom: zColor(),
    trunk: zColor(),
  }),
  flowers: z.object({ orange: zColor(), pink: zColor() }),
  garden: z.object({ lawn: zColor(), lawnLines: zColor(), path: zColor(), gravel: zColor() }),
  night: z.object({ tint: zColor(), strength: unit() }),
  chandeliers: z.object({
    show: z.boolean(),
    night: zColor(),
    finale: zColor(),
    crystal: zColor(),
    flame: zColor(),
  }),
  garlands: z.object({
    show: z.boolean(),
    marigold: zColor(),
    leaf: zColor(),
    bell: zColor(),
    bead: zColor(),
    sway: unit(6, 0.1),
  }),
  procession: z.object({
    show: z.boolean(),
    walkers: count(8),
    speed: unit(8, 0.1),
    scale: zSlider({ min: 0.6, max: 1.4, step: 0.01 }),
    elephant: zColor(),
    blanket: zColor(),
    howdah: zColor(),
    trim: zColor(),
    kurta: zColor(),
    turban: zColor(),
    skin: zColor(),
  }),
  look: z.object({ showBackdrop: z.boolean() }),
  motion: motionSchema,
});

