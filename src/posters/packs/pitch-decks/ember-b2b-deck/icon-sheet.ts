const iconSheetSpec = {
  colors: {
    background: { value: E.paper, hint: 'Page' },
    primary: { value: E.ink, hint: 'Every icon' },
  },
} as const satisfies ThemeSpec;

export const iconSheet = (start: number) =>
  themed(SW, SH, iconSheetSpec, (t) => [
    background(t.color('background')),
    Array.from({ length: 78 }, (_, index) => {
      const name = ICONS[(index + start) % ICONS.length] ?? 'star';
      return icon(
        name,
        170 + (index % 13) * 128,
        188 + Math.floor(index / 13) * 128,
        64,
        t.color('primary'),
        { strokeWidth: 2 },
      );
    }),
  ]);
